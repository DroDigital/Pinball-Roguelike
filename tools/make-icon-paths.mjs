const src = process.argv[2];
const json = src
  ? JSON.parse(readFileSync(src, 'utf8'))
  : await (await fetch('https://unpkg.com/@iconify-json/game-icons/icons.json')).json();

const out = {};
const missing = [];
for (const [id, names] of Object.entries(ITEM_ICONS)) {
  const name = names.find((n) => json.icons[n]);
  if (!name) {
    missing.push(id);
    continue;
  }
  const icon = json.icons[name];
  const w = icon.width ?? json.width ?? 512;
  const h = icon.height ?? json.height ?? 512;
  if (w !== 512 || h !== 512) throw new Error(`${name} is ${w}x${h}`);
  out[id] = { name, body: icon.body.replace(/\s*fill="currentColor"/g, '') };
}
if (missing.length) throw new Error(`no icon found for: ${missing.join(', ')}`);

const lines = Object.entries(out).map(
  ([id, { name, body }]) => `  // ${name}\n  ${id}: ${JSON.stringify(body)},`,
);
writeFileSync(
  new URL('../src/app/icon-paths.ts', import.meta.url),
  `// Generated by tools/make-icon-paths.mjs: do not edit by hand.
// Icons from game-icons.net by Lorc, Delapouite and contributors, CC BY 3.0
// (https://creativecommons.org/licenses/by/3.0/). 512 x 512 viewBox, filled with currentColor.
export const ICON_BODIES: Record<string, string> = {
${lines.join('\n')}
};
`,
);
console.log(`wrote ${Object.keys(out).length} icons`);
for (const [id, { name }] of Object.entries(out)) console.log(`  ${id} -> ${name}`);
