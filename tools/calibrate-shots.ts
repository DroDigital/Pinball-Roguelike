/**
 * Calibrate the bot's cradle shots: for each flipper, sweep the release->flip delay and record
 * the outcome; pick the centre of the widest window per target. Writes src/bot/shot-table.ts.
 */
import { writeFileSync } from 'node:fs';
import { makeSim, cradle, shotFromCradle, type ShotOutcome } from '../src/bot/scenarios';

const TARGETS = ['chute', 'perimeter', 'hole', 'cellblock'] as const;
const table: Record<string, Record<string, number>> = { left: {}, right: {} };
const report: string[] = [];
for (const side of ['left', 'right'] as const) {
  const res: ShotOutcome[] = [];
  const D0 = 40;
  const D1 = 300;
  for (let d = D0; d <= D1; d++) {
    const sim = makeSim(3);
    cradle(sim, side);
    res.push(shotFromCradle(sim, side, d));
  }
  for (const t of TARGETS) {
    let bestLen = 0;
    let bestStart = -1;
    let run = 0;
    for (let i = 0; i <= res.length; i++) {
      if (i < res.length && res[i] === t) run++;
      else {
        if (run > bestLen) {
          bestLen = run;
          bestStart = i - run;
        }
        run = 0;
      }
    }
    if (bestLen >= 3) {
      table[side][t] = D0 + bestStart + Math.floor(bestLen / 2);
      report.push(`${side} ${t}: delay ${table[side][t]} (window ${bestLen} steps)`);
    }
  }
}
console.log(report.join('\n'));
const src = `// Generated by tools/calibrate-shots.ts — release->flip delays (steps) for cradle shots.
export type ShotTarget = 'chute' | 'perimeter' | 'hole' | 'cellblock';
export const SHOT_TABLE: Record<'left' | 'right', Partial<Record<ShotTarget, number>>> = ${JSON.stringify(table, null, 2)};
`;
writeFileSync('src/bot/shot-table.ts', src);
