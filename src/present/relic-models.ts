/**
 * Relic models: one low-poly sculpture per charm and contraband, described as data (a handful
 * of scaled primitives each) so the whole set costs no asset bytes. `relics.ts` merges a
 * recipe into one flat-shaded, vertex-coloured mesh. Units are arbitrary; every model is
 * normalised to a unit box standing on y = 0.
 */

