export interface PixelFont {
  w: number;
  h: number;
  spacing: number;
  glyph(ch: string): number[];
}

export const FONT_LARGE: PixelFont = {
  w: 5,
  h: 7,
  spacing: 1,
  glyph: (ch) => F57[ch] ?? F57[ch.toUpperCase()] ?? F57['?'],
};

export const FONT_SMALL: PixelFont = {
  w: 3,
  h: 5,
  spacing: 1,
  glyph: (ch) => F35[ch] ?? F35[ch.toUpperCase()] ?? F35['?'],
};

export function textWidth(font: PixelFont, text: string, scale = 1): number {
  return text.length ? (text.length * (font.w + font.spacing) - font.spacing) * scale : 0;
}
